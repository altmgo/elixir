# two types of numbers: int and float
integer = 3

float = 3.14 #64-bit double precision float-point format

# Operations:
# You can mix them together in operations.
2 * 3 # => 6
2 * 3.14 # => 6.28

# Division will always be float, even if using 2 integers
6 / 2 # => 3.0

# float -> int: use the function trunc/1
trunc(3.0) # => 3
